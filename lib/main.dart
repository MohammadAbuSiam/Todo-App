import 'package:firebase_auth/firebase_auth.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';
import 'package:get/get.dart';

import 'core/app_theme.dart';
import 'database/local_storage.dart';
import 'firebase_options.dart'; // generated by `flutterfire configure`
import 'routes/app_routes.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();

  await Firebase.initializeApp(
    options: DefaultFirebaseOptions.currentPlatform,
  );

  // Anonymous sign-in: gives each device its own uid (no login screen needed).
  if (FirebaseAuth.instance.currentUser == null) {
    await FirebaseAuth.instance.signInAnonymously();
  }

  // Name already saved -> Home, otherwise Welcome.
  final userName = await LocalStorage().getUserName();
  runApp(TudooApp(
    initialRoute: userName == null ? AppRoutes.welcome : AppRoutes.home,
  ));
}

class TudooApp extends StatelessWidget {
  final String initialRoute;
  const TudooApp({super.key, required this.initialRoute});

  @override
  Widget build(BuildContext context) {
    return GetMaterialApp(
      title: 'Tudoo',
      debugShowCheckedModeBanner: false,
      theme: AppTheme.light,
      initialRoute: initialRoute,
      getPages: AppRoutes.pages,
    );
  }
}
